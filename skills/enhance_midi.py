#!/usr/bin/env python3
"""
Enhance an existing composition or MIDI file.

Operations work on Composition objects, so they apply equally to compositions
generated by this skill and to MIDI files read with import_midi.py.

    humanize        random small timing/velocity variation (less robotic)
    quantize        snap note starts (and optionally lengths) to a grid
    transpose       shift pitches by semitones (drum tracks are skipped)
    set_instrument  change a track's GM instrument
    set_mix         set volume / pan / reverb / chorus for a track
    dynamics        rescale velocities into a range (compress / expand)

Usage (CLI):
    python skills/enhance_midi.py in.mid out.mid '[{"op":"humanize"},{"op":"set_mix","track":0,"reverb":50}]'
"""

import json
import random
import sys
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Union

sys.path.insert(0, str(Path(__file__).parent.parent))

from midi_types.music import Composition, Note, Track
from midi_types.notation import parse_duration, parse_pitch, pitch_name, split_pitches
from skills.generate_midi import generate_midi, is_drum_track
from skills.import_midi import import_midi

TrackSel = Optional[Union[int, Iterable[int]]]


def _select(comp: Composition, tracks: TrackSel) -> List[Track]:
    if tracks is None:
        return list(comp.tracks)
    if isinstance(tracks, int):
        tracks = [tracks]
    return [comp.tracks[i] for i in tracks]


def make_absolute(comp: Composition) -> Composition:
    """Give every note an explicit start and length in beats (rests are dropped)."""
    for track in comp.tracks:
        new_notes = []
        for start, beats, note in track.timeline():
            if note.is_rest:
                continue
            new_notes.append(Note(pitch=note.pitch, duration=None, velocity=note.velocity,
                                  start=start, beats=beats))
        track.notes = new_notes
    return comp


def _velocity(note: Note, track: Track) -> int:
    if note.velocity is not None:
        return note.velocity
    return track.velocity if track.velocity is not None else 100


def humanize(comp: Composition, timing: float = 0.02, velocity: int = 8,
             tracks: TrackSel = None, seed: Optional[int] = None) -> Composition:
    """
    Add small random variation to note timing and velocity.

    Args:
        timing: max shift in beats (0.02 beat ~ 10 ms at 120 BPM)
        velocity: max velocity change (+/-)
    """
    rng = random.Random(seed)
    make_absolute(comp)
    for track in _select(comp, tracks):
        for note in track.notes:
            if timing:
                note.start = round(max(0.0, note.start + rng.uniform(-timing, timing)), 4)
            if velocity:
                v = _velocity(note, track) + rng.randint(-velocity, velocity)
                note.velocity = max(1, min(127, v))
        track.notes.sort(key=lambda n: n.start)
    return comp


def quantize(comp: Composition, grid: str = "16", strength: float = 1.0,
             lengths: bool = False, tracks: TrackSel = None) -> Composition:
    """
    Snap note starts to a rhythmic grid.

    Args:
        grid: duration notation of the grid ("16" = sixteenth, "8", "T8", ...)
        strength: 0..1, how far to move toward the grid (1 = fully)
        lengths: also snap note lengths (minimum one grid step)
    """
    step = parse_duration(grid)
    make_absolute(comp)
    for track in _select(comp, tracks):
        for note in track.notes:
            target = round(note.start / step) * step
            note.start = round(note.start + (target - note.start) * strength, 4)
            if lengths:
                target_len = max(step, round(note.beats / step) * step)
                note.beats = round(note.beats + (target_len - note.beats) * strength, 4)
        track.notes.sort(key=lambda n: n.start)
    return comp


def transpose(comp: Composition, semitones: int, tracks: TrackSel = None) -> Composition:
    """Shift pitches by semitones. Drum tracks are never transposed."""
    for track in _select(comp, tracks):
        if is_drum_track(track):
            continue
        for note in track.notes:
            if note.is_rest:
                continue
            shifted = []
            for p in split_pitches(note.pitch):
                n = parse_pitch(p) + semitones
                if not 0 <= n <= 127:
                    raise ValueError(f"Transposing {p} by {semitones} leaves MIDI range")
                shifted.append(pitch_name(n))
            note.pitch = shifted[0] if len(shifted) == 1 else shifted
    return comp


def set_instrument(comp: Composition, track: int, instrument: str) -> Composition:
    """Change the GM instrument of one track."""
    t = comp.tracks[track]
    t.instrument = instrument
    if instrument.lower() not in ("drums", "drum-kit", "percussion"):
        t.drums = False
        if t.channel == 9:
            t.channel = None
    return comp


def set_mix(comp: Composition, track: int, volume: Optional[int] = None,
            pan: Optional[int] = None, reverb: Optional[int] = None,
            chorus: Optional[int] = None) -> Composition:
    """Set mix controllers (0-127) for one track. pan: 0 left, 64 center, 127 right."""
    t = comp.tracks[track]
    for key, value in (("volume", volume), ("pan", pan), ("reverb", reverb), ("chorus", chorus)):
        if value is not None:
            setattr(t, key, max(0, min(127, int(value))))
            # A time-0 CC in `controls` would override the field; drop it
            cc = {"volume": 7, "pan": 10, "reverb": 91, "chorus": 93}[key]
            t.controls = [c for c in t.controls
                          if not (c.get("cc") == cc and float(c.get("time", 0)) == 0)]
    return comp


def dynamics(comp: Composition, low: int = 50, high: int = 115,
             tracks: TrackSel = None) -> Composition:
    """
    Linearly rescale each track's velocities into [low, high].

    Useful for flat MIDI (all notes 100) after humanize, or to tame/expand
    extreme dynamics in imported files.
    """
    for track in _select(comp, tracks):
        notes = [n for n in track.notes if not n.is_rest]
        if not notes:
            continue
        vels = [_velocity(n, track) for n in notes]
        vmin, vmax = min(vels), max(vels)
        for note, v in zip(notes, vels):
            if vmax == vmin:
                new = (low + high) / 2
            else:
                new = low + (v - vmin) * (high - low) / (vmax - vmin)
            note.velocity = max(1, min(127, round(new)))
    return comp


OPERATIONS = {
    "humanize": humanize,
    "quantize": quantize,
    "transpose": transpose,
    "set_instrument": set_instrument,
    "set_mix": set_mix,
    "dynamics": dynamics,
}


def apply_operations(comp: Composition, operations: List[Dict[str, Any]]) -> Composition:
    """Apply a list of {"op": name, **kwargs} operations in order."""
    for op in operations:
        args = dict(op)
        name = args.pop("op")
        if name not in OPERATIONS:
            raise ValueError(f"Unknown operation {name!r}. Available: {', '.join(OPERATIONS)}")
        comp = OPERATIONS[name](comp, **args)
    return comp


def enhance_dict(data: Dict[str, Any], operations: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Apply operations to a composition dictionary and return the new dictionary."""
    return apply_operations(Composition.from_dict(data), operations).to_dict()


def enhance_midi_file(input_path: str, operations: List[Dict[str, Any]],
                      output_path: Optional[str] = None) -> str:
    """
    Import a MIDI file, apply operations, and write a new MIDI file.

    Default output: output/<name>_enhanced.mid (the input is never overwritten
    unless output_path points at it explicitly).
    """
    comp = Composition.from_dict(import_midi(input_path))
    comp = apply_operations(comp, operations)
    if output_path is None:
        out_dir = Path(__file__).parent.parent / "output"
        output_path = str(out_dir / f"{Path(input_path).stem}_enhanced.mid")
    return generate_midi(comp, output_path)


if __name__ == "__main__":
    if len(sys.argv) < 4:
        print(__doc__)
        sys.exit(1)
    result = enhance_midi_file(sys.argv[1], json.loads(sys.argv[3]), sys.argv[2])
    print(f"Enhanced: {result}")
